/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS harness transpiles route modules with isolated dependency mocks. */
const assert = require("node:assert/strict")
const test = require("node:test")
const fs = require("node:fs")
const path = require("node:path")
const Module = require("node:module")
const ts = require("typescript")

function loadTS(relativePath, mocks = {}) {
  const filename = path.resolve(__dirname, "../src", relativePath)
  const mod = new Module(filename, module)
  mod.filename = filename
  mod.paths = Module._nodeModulePaths(path.dirname(filename))
  const originalRequire = mod.require.bind(mod)
  mod.require = (id) => {
    if (Object.hasOwn(mocks, id)) return mocks[id]
    if (id.startsWith("@/")) return loadTS(`${id.slice(2)}.ts`, mocks)
    return originalRequire(id)
  }
  mod._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true },
  }).outputText, filename)
  return mod.exports
}

const { buildOpportunityWhere, QUOTE_STATUSES, EL_STATUSES, PRODUCTION_STATUSES } = loadTS("shared/lib/utils.ts")
// Evaluate the small subset of Prisma filters generated by the list query.
function matches(record, where) {
  return Object.entries(where).every(([key, value]) => {
    if (key === "AND") return value.every((v) => matches(record, v))
    if (key === "OR") return value.some((v) => matches(record, v))
    if (value && typeof value === "object") {
      if (value.in) return value.in.includes(record[key])
      if (value.contains) return (record[key] ?? "").toLowerCase().includes(value.contains.toLowerCase())
    }
    return record[key] === value
  })
}

for (const statuses of [QUOTE_STATUSES, EL_STATUSES, PRODUCTION_STATUSES]) {
  test(`archive filters respect workflow scope: ${statuses[0]}`, () => {
    const active = { status: statuses[0], isArchived: false, title: "Pump" }
    const archived = { ...active, isArchived: true }
    assert.equal(matches(active, buildOpportunityWhere("", ["ARCHIVED"], statuses)), true)
    assert.equal(matches(archived, buildOpportunityWhere("", ["ARCHIVED"], statuses)), false)
    assert.equal(matches(archived, buildOpportunityWhere("", statuses, statuses)), true)
    assert.equal(matches(active, buildOpportunityWhere("", statuses, statuses)), false)
    assert.equal(matches(archived, buildOpportunityWhere("pump", [], statuses)), true)
    assert.equal(matches(archived, buildOpportunityWhere("missing", [], statuses)), false)
    assert.equal(matches({ ...archived, status: "CANCELLED" }, buildOpportunityWhere("", [], statuses)), false)
  })
}

const { committedAgreementAmount } = loadTS("modules/adhoc/amounts.ts")
test("archiving excludes approval and finance amounts; restoring reinstates the original commitment", () => {
  const packages = [
    { isArchived: false, status: "APPROVED", approvedAmount: "200", financeAmount: null },
    { isArchived: false, status: "CLOSED_FINANCE", approvedAmount: "300", financeAmount: "250" },
    { isArchived: false, status: "CANCELLED", approvedAmount: "500", financeAmount: null },
  ]
  assert.equal(committedAgreementAmount(packages), 450)
  packages[0].isArchived = true
  assert.equal(committedAgreementAmount(packages), 250)
  packages[1].isArchived = true
  assert.equal(committedAgreementAmount(packages), 0)
  packages[0].isArchived = false
  packages[1].isArchived = false
  assert.equal(committedAgreementAmount(packages), 450)
})

for (const [routePath, model] of [
  ["app/api/opportunities/[id]/route.ts", "opportunity"],
  ["app/api/adhoc/deliverables/[id]/route.ts", "adhocDeliverable"],
]) {
  test(`${model}: archive round trip, validation, permissions and workflow preservation`, async () => {
    let allowed = true
    const initial = { id: "one", title: "Pump", status: model === "opportunity" ? "IN_PRODUCTION" : "CLOSED_FINANCE", isArchived: false,
      approvedAmount: "300", financeAmount: "250", approvedAt: "2026-10-01", deliveredAt: "2026-10-10" }
    let record = { ...initial }
    const writes = []
    const logs = []
    const mocks = {
      "@/shared/lib/db": { db: {
        [model]: {
          findUnique: async () => record,
          update: async ({ data }) => { writes.push(data); record = { ...record, ...data }; return record },
        },
        comment: { create: async () => ({}) },
      } },
      "@/shared/lib/api": {
        requireSession: async () => ({ session: { user: { id: "user", role: "USER" } }, error: null }),
        hasSectionAccess: () => allowed,
      },
      "@/shared/lib/system-log": { writeLog: async (entry) => logs.push(entry) },
      "@/shared/lib/notify": { scheduleNotification: async () => {} },
    }
    const { PATCH } = loadTS(routePath, mocks)
    const patch = (body) => PATCH(new Request("http://localhost/test", {
      method: "PATCH", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body),
    }), { params: Promise.resolve({ id: "one" }) })
    assert.equal((await patch({ isArchived: true })).status, 200)
    assert.equal(record.isArchived, true)
    assert.equal((await patch({ status: "DELIVERED" })).status, 409)
    assert.equal((await patch({ isArchived: true })).status, 200)
    assert.equal(logs.length, 1)
    assert.equal((await patch({ isArchived: "false" })).status, 400)
    assert.equal((await patch({ isArchived: false, title: "Changed" })).status, 400)
    allowed = false
    assert.equal((await patch({ isArchived: false })).status, 403)
    assert.equal(record.isArchived, true)
    allowed = true
    assert.equal((await patch({ isArchived: false })).status, 200)
    assert.deepEqual(record, initial)
    assert.equal(logs.length, 2)
    assert.ok(writes.every((data) => Object.keys(data).length === 1 && typeof data.isArchived === "boolean"))
  })
}

test("global search includes archived results with clear badges and original destinations", async () => {
  const { GET } = loadTS("app/api/search/route.ts", {
    "@/shared/lib/db": { db: {
      opportunity: { findMany: async () => [{ id: "opp", title: "Pump", status: "EL_FULLY_SIGNED", isArchived: true, customer: "Customer" }] },
      adhocDeliverable: { findMany: async () => [{ id: "wp", title: "Pump", status: "APPROVED", isArchived: true, agreement: { id: "agreement", title: "Agreement" } }] },
    } },
    "@/shared/lib/api": { requireSession: async () => ({ session: { user: {} }, error: null }), hasSectionAccess: () => true },
  })
  const response = await GET({ nextUrl: new URL("http://localhost/api/search?q=pump") })
  const body = await response.json()
  assert.equal(body.opportunities[0].status, "ARCHIVED")
  assert.equal(body.opportunities[0].basePath, "/els")
  assert.equal(body.adhoc[0].status, "ARCHIVED")
  assert.equal(body.adhoc[0].href, "/adhoc?agreement=agreement&deliverable=wp")
})
